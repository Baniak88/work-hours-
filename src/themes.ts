export function isLightTheme(name: ThemeName): boolean {
  return name === "light" || name === "pastel";
}
export function themeColor(value: string, name: ThemeName = "navy"): string {
  if (!/^#[a-f\d]{6}([a-f\d]{2})?$/i.test(value)) return value;
  const base = value.slice(0, 7).toUpperCase(),
    suffix = value.slice(7),
    p = themes[name];
  const colors: Record<string, string> = {
    "#111214": p.bg,
    "#1C1D20": p.card,
    "#282A2F": p.raised,
    "#34363C": p.line,
    "#F4F4F5": p.text,
    "#A0A3AB": p.muted,
    "#DCE2EA": p.accent,
    "#AEBED1": p.blue,
    "#ECAAA5": p.red,
    "#17181B": p.inner,
    "#151619": p.inner,
    "#222428": p.raised,
    "#2C2E33": p.raised,
    "#2A2C31": p.raised,
    "#2B2E34": p.raised,
    "#292C32": p.raised,
    "#35383F": p.selected,
    "#3A3D45": p.selected,
    "#2B2E35": p.selected,
    "#C7C9CD": p.day,
    "#9DAAC0": p.night,
    "#AFB2BB": p.muted,
    "#92969F": p.muted,
    "#BCC0C8": p.muted,
    "#81848C": p.muted,
    "#7F838D": p.muted,
    "#9CA7B8": p.accent,
    "#33363D": name === "light" || name === "pastel" ? "#EEF2FA" : p.bg,
    "#452A29": name === "light" || name === "pastel" ? "#FFE5E7" : "#3A1E1F",
    "#23252A": p.inner,
    "#303138": p.raised,
    "#30333A": p.raised,
    "#353841": p.selected,
    "#393C44": p.selected,
    "#596779": name === "light" || name === "pastel" ? "#D8E5F8" : p.night,
    "#5C5E64": name === "light" || name === "pastel" ? "#FFFFFF" : p.day,
    "#606977": p.muted,
    "#737D8C": p.muted,
    "#858D9B": p.muted,
    "#BCB7AD": p.muted,
  };
  return (colors[base] ?? value.slice(0, 7)) + suffix;
}
